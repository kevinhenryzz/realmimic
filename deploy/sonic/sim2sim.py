@dataclass
class Sonic:
    """Paths of a build.sh + setup_sim.sh SONIC work directory."""

    workdir: Path

    @property
    def src(self) -> Path:
        return self.workdir / "GR00T-WholeBodyControl"

    @property
    def deploy(self) -> Path:
        return self.src / "gear_sonic_deploy"

    @property
    def binary(self) -> Path:
        return self.deploy / "target/release/g1_deploy_onnx_ref"

    @property
    def planner(self) -> Path:
        return self.deploy / "planner/target_vel/V2/planner_sonic.onnx"

    @property
    def sim_python(self) -> Path:
        return self.workdir / ".venv_sim/bin/python"

    @property
    def clips(self) -> Path:
        return self.workdir / "reference/example"

    @property
    def stock_scene(self) -> Path:
        return self.workdir / "sonic_g1_model/scene_43dof.xml"

    def check(self) -> None:
        for p in (self.binary, self.planner, self.sim_python, self.clips, self.stock_scene):
            if not p.exists():
                sys.exit(f"missing {p}: run deploy/sonic/build.sh and deploy/sonic/setup_sim.sh")


@dataclass
class Policy:
    name: str
    decoder: Path
    obs_config: Path
    encoder: Path | None = None
    flags: list[str] = field(default_factory=list)
    manifest: dict[str, Any] = field(default_factory=dict)


def resolve_policy(bundle: str, sonic: Sonic, engines: Path, run: Path) -> Policy:
    if bundle == RELEASE:
        rel = sonic.deploy / "policy/release"
        return Policy(RELEASE, rel / "model_decoder.onnx", rel / "observation_config.yaml",
                      encoder=rel / "model_encoder.onnx")  # fmt: skip
    src = Path(bundle)
    manifest = json.loads((src / "manifest.json").read_text())
    env = (src / "launch.env").read_text()
    m = re.search(r'^REALMIMIC_SONIC_FLAGS="(.*)"$', env, re.MULTILINE)
    flags = shlex.split(m.group(1)) if m else []
    # TensorRT caches its engine next to the ONNX file: keep a shared copy keyed by content so the
    # engine is built once per policy, and the bundle directory is only ever read.
    digest = hashlib.sha256((src / "policy.onnx").read_bytes()).hexdigest()[:16]
    cached = engines / digest / "policy.onnx"
    if not cached.exists():
        cached.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(src / "policy.onnx", cached)
    (run / "bundle").mkdir()
    for name in ("observation_config.yaml", "launch.env", "manifest.json"):
        shutil.copyfile(src / name, run / "bundle" / name)
    return Policy(str(src.resolve()), cached, run / "bundle/observation_config.yaml",
                  flags=flags, manifest=manifest)  # fmt: skip


def write_scene(robot: str, sonic: Sonic, run: Path) -> Path:
    if robot == STOCK:
        return sonic.stock_scene
    from realmimic.robots import get_robot_spec
    from realmimic.robots.sim2sim import write_sim2sim_mjcf

    return write_sim2sim_mjcf(get_robot_spec(robot), run / "model")


def clip_seconds(clip_dir: Path) -> float:
    with (clip_dir / "joint_pos.csv").open() as f:
        return (sum(1 for _ in f) - 1) * 0.02


# ---------------------------------------------------------------------------- run


class Session:
    def __init__(self, sim: Proc, deploy: Proc, gpu_abort_mib: int):
        self.sim, self.deploy = sim, deploy
        self.gpu_abort_mib = gpu_abort_mib
        self.events: list[dict[str, Any]] = []
        self.phases: list[dict[str, Any]] = []
        self.release_t: float | None = None
        self.abort: str | None = None
        self.gpu_peak_mib = 0
        self._stop = threading.Event()
        threading.Thread(target=self._watch_gpu, daemon=True).start()

    def _watch_gpu(self) -> None:
        while not self._stop.wait(1.0):
            try:
                free, mine = gpu_free_mib(), gpu_used_by(self.deploy.p.pid)
            except (OSError, subprocess.CalledProcessError, ValueError):
                continue
            self.gpu_peak_mib = max(self.gpu_peak_mib, mine)
            if free < self.gpu_abort_mib and self.deploy.alive():
                self.abort = f"GPU free memory {free} MiB < {self.gpu_abort_mib} MiB"
                os.killpg(self.deploy.p.pid, signal.SIGKILL)

    def log(self, kind: str, detail: str = "") -> float:
        t = time.monotonic()
        self.events.append({"t": t, "kind": kind, "detail": detail})
        print(f"[sim2sim {t:.2f}] {kind} {detail!r}", flush=True)
        return t

    def check(self) -> bool:
        """False once the session must stop (fall, process exit, GPU guard)."""
        if self.abort:
            return False
        fall = self.sim.find(r"^SIM fall")
        if fall and self.release_t is not None:
            self.abort = fall
        elif not self.deploy.alive():
            self.abort = f"runtime exited with {self.deploy.p.returncode}"
        elif not self.sim.alive():
            self.abort = f"simulator exited with {self.sim.p.returncode}"
        return self.abort is None

    def sleep(self, seconds: float) -> bool:
        end = time.monotonic() + seconds
        while time.monotonic() < end:
            if not self.check():
                return False
            time.sleep(min(0.05, max(0.0, end - time.monotonic())))
        return self.check()

    def run(self, steps: list[Step]) -> None:
        for step in steps:
            if not self.check():
                break
            if isinstance(step, Phase):
                self.phases.append({"name": step.name, "t": self.log("phase", step.name)})
            elif isinstance(step, Key):
                self.log("key", step.chars)
                self.deploy.send(step.chars)
            elif isinstance(step, Release):
                self.sim.send("release\n")
                if not self.sim.wait_for(r"^SIM released", 5.0):
                    self.abort = "simulator did not confirm the band release"
                    break
                self.release_t = self.log("release")
            elif isinstance(step, Expect):
                if not self.deploy.wait_for(step.pattern, step.timeout):
                    self.abort = f"runtime never printed {step.pattern!r}"
                    break
                self.log("expect", step.pattern)
            elif isinstance(step, Wait) and not self.sleep(step.seconds):
                break

    def finish(self) -> None:
        self._stop.set()


@contextlib.contextmanager
def exclusive_session(path: Path = Path("/tmp/realmimic-sim2sim.lock")):
    """One session per machine: runtime and simulator talk DDS on ``lo`` with a fixed domain, so two
    concurrent sessions would read each other's LowState / LowCmd. Later sessions wait here."""
    with open(path, "w") as lock:
        try:
            fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError:
            print("[sim2sim] another session is running; waiting for it", flush=True)
            fcntl.flock(lock, fcntl.LOCK_EX)
        yield


def run(args: argparse.Namespace) -> Path:
    sonic = Sonic(Path(args.sonic_workdir).expanduser())
    sonic.check()
    out = Path(args.out or REPO / "runs/sim2sim" / time.strftime(
        f"%Y%m%d_%H%M%S_{args.robot}_{Path(args.bundle).name}_{args.session}")).resolve()  # fmt: skip
    out.mkdir(parents=True, exist_ok=False)
    engines = Path(args.engine_cache).expanduser().resolve()

    from realmimic.obs.sonic import DEFAULT_ANGLES

    scene = write_scene(args.robot, sonic, out)
    policy = resolve_policy(args.bundle, sonic, engines, out)
    # The runtime needs at least one reference clip even in planner sessions. Default: SONIC's first example
    # squat, the clip all our reported sim-to-sim sessions loaded (picked by category, not by name).
    if args.clip is None:
        examples = sorted(p.name for p in sonic.clips.iterdir() if p.is_dir())
        args.clip = next((c for c in examples if c.startswith("squat_") and not c.endswith("_M")), examples[0])
    clip = sonic.clips / args.clip
    (out / "motions").mkdir()
    (out / "motions" / args.clip).symlink_to(clip)

    free = gpu_free_mib()
    if free < args.gpu_min_free_mib:
        sys.exit(f"GPU free memory {free} MiB < {args.gpu_min_free_mib} MiB: not starting runtime")

    sim = Proc("sim", [
        str(sonic.sim_python), str(HERE / "sonic_sim.py"), "--scene", str(scene),
        "--out", str(out / "sim.npz"), "--init-joint-pos=" + ",".join(map(str, DEFAULT_ANGLES)),
        "--sim-dt", str(args.sim_dt), "--lowstate-dt", str(args.lowstate_dt),
        "--seed", str(args.seed), *PERTURBATIONS[args.perturb],
    ], out / "sim.log", cwd=sonic.src, env={**os.environ, "PYTHONPATH": str(sonic.src)})  # fmt: skip
    if not sim.wait_for(r"^SIM ready", 60.0):
        sim.stop("quit\n", 10.0)
        sys.exit(f"simulator did not start, see {out / 'sim.log'}")

    libs = [str(Path(p).expanduser() / "lib") for p in (args.tensorrt_root, args.onnxruntime_root)]
    libs.append(str(Path(args.cuda_root).expanduser() / "lib64"))
    env = {
        **os.environ,
        "LD_LIBRARY_PATH": ":".join(libs + [os.environ.get("LD_LIBRARY_PATH", "")]),
    }
    cmd = [
        str(sonic.binary), "lo", str(policy.decoder), str(out / "motions"),
        "--obs-config", str(policy.obs_config), "--planner-file", str(sonic.planner),
        "--input-type", "keyboard", "--output-type", "zmq", "--disable-crc-check",
        "--enable-csv-logs", "--logs-dir", str(out / "deploy_logs"),
        "--target-motion-logfile", str(out / "target_motion.csv"),
        "--policy-input-logfile", str(out / "policy_input.csv"),
    ]  # fmt: skip
    if policy.encoder:
        cmd += ["--encoder-file", str(policy.encoder)]
    cmd += policy.flags + shlex.split(args.extra_flags)
    deploy = Proc("deploy", cmd, out / "deploy.log", cwd=sonic.deploy, env=env)

    session = Session(sim, deploy, args.gpu_abort_free_mib)
    start = session.log("start")
    try:
        if deploy.wait_for(r"Init Done", args.init_timeout):
            steps = (
                planner_session(args.idle) if args.session == "planner"
                else clip_session(args.idle, clip_seconds(clip))
            )  # fmt: skip
            session.run(steps)
        elif session.check():
            session.abort = f"runtime not ready after {args.init_timeout} s"
    except KeyboardInterrupt:
        session.abort = "interrupted"
    finally:
        end = session.log("end", session.abort or "")
        deploy_rc = deploy.stop("o", 20.0)  # O: stop control (damping) and exit
        sim.stop("quit\n", 60.0)
        session.finish()

    meta = {
        "robot": args.robot, "bundle": policy.name, "session": args.session, "clip": args.clip,
        "perturb": args.perturb, "seed": args.seed,
        "scene": str(scene), "obs_config": str(policy.obs_config), "runtime_flags": policy.flags,
        "extra_flags": args.extra_flags, "deploy_cmd": cmd, "deploy_returncode": deploy_rc,
        "start_t": start, "end_t": end, "release_t": session.release_t,
        "phases": session.phases, "events": session.events,
        "aborted": session.abort is not None, "abort_reason": session.abort,
        "gpu_free_mib_at_start": free, "gpu_peak_mib": session.gpu_peak_mib,
        "bundle_manifest": {k: v for k, v in policy.manifest.items() if k != "train_config"},
    }  # fmt: skip
    (out / "session.json").write_text(json.dumps(meta, indent=2))
    report(out)
    return out


# ---------------------------------------------------------------------------- reports


def report(run_dir: Path) -> None:
    from realmimic.eval import sim2sim, sonic_obs_check

    metrics = sim2sim.compute_report(run_dir)
    (run_dir / "metrics.json").write_text(json.dumps(metrics, indent=2))
    print(json.dumps(sim2sim.summary_row(metrics)))

    session = json.loads((run_dir / "session.json").read_text())
    logs = run_dir / "deploy_logs"
    if not (run_dir / "policy_input.csv").exists() or not (logs / "q.csv").exists():
        return
    inputs = sim2sim.read_rows_csv(run_dir / "policy_input.csv")
    states = {k: sim2sim.read_state_csv(logs / f"{k}.csv")[1]
              for k in ("q", "dq", "base_quat", "base_ang_vel", "action")}  # fmt: skip
    target = sim2sim.read_rows_csv(run_dir / "target_motion.csv")
    n = min(len(inputs), len(target), *(len(v) for v in states.values()))
    order, extra = sonic_obs_check.observation_order(session["obs_config"])
    expected = sonic_obs_check.expected_terms(
        states["q"][:n], states["dq"][:n], states["base_quat"][:n], states["base_ang_vel"][:n],
        states["action"][:n], target[:n],
    )  # fmt: skip
    check = sonic_obs_check.compare(inputs[:n], order, expected, extra)
    (run_dir / "obs_check.json").write_text(json.dumps(check, indent=2))
    bad = {k: v["frac_out_of_tol"] for k, v in check.items() if v.get("frac_out_of_tol")}
    print(f"obs check ({n} ticks): {'all checked terms within tolerance' if not bad else bad}")
    if session["bundle"] == RELEASE and session["session"] == "clip":
        release_check(run_dir, session, states, inputs[:n], target[:n], n)
    elif session["bundle"] != RELEASE:
        check = sonic_obs_check.bundle_policy_check(
            Path(session["bundle"]) / "policy.onnx", inputs[:n], states["action"][:n]
        )
        (run_dir / "policy_check.json").write_text(json.dumps(check, indent=2))
        a = check["action"]
        print(f"policy check ({a['ticks']} ticks): engine vs ONNX max abs err {a['max_abs_err']:.2e}, "
              f"{a['ticks_out_of_tol']} ticks out of tolerance")


def release_check(
    run_dir: Path, session: dict[str, Any], states: dict[str, Any], inputs: Any, target: Any, n: int
) -> None:
    """``release_check.json``: SONIC's release policy rerun in torch on the logged clip session
    (``sonic_obs_check.release_policy_check``)."""
    import numpy as np

    from realmimic.eval import sim2sim, sonic_obs_check
    from realmimic.eval.sonic_release_policy import SonicReleasePolicy

    logs = run_dir / "deploy_logs"
    for k in ("token_state", "motion_playing"):
        states[k] = sim2sim.read_state_csv(logs / f"{k}.csv")[1]
    clip_dir = run_dir / "motions" / session["clip"]
    rows = lambda name: np.loadtxt(clip_dir / name, delimiter=",", skiprows=1, ndmin=2)
    clip = {
        "joint_pos": rows("joint_pos.csv"),
        "joint_vel": rows("joint_vel.csv"),
        "root_quat": rows("body_quat.csv")[:, :4],  # body 0 = pelvis
    }
    policy = SonicReleasePolicy(Path(session["obs_config"]).parent, device="cpu")
    check = sonic_obs_check.release_policy_check(
        policy, *(states[k][:n] for k in ("q", "dq", "base_quat", "base_ang_vel", "action")),
        states["token_state"][:n], states["motion_playing"][:n, 0], inputs, target, clip,
    )  # fmt: skip
    (run_dir / "release_check.json").write_text(json.dumps(check, indent=2))
    bad = {k: v["ticks_out_of_tol"] for k, v in check.items() if v.get("ticks_out_of_tol")}
    print(f"release policy check: {'all within tolerance' if not bad else bad}")


def summarize(run_dirs: list[Path]) -> None:
    from realmimic.eval.sim2sim import summary_row

    rows = [summary_row(json.loads((d / "metrics.json").read_text())) for d in run_dirs]
    keys = list(dict.fromkeys(k for r in rows for k in r))
    print("| " + " | ".join(keys) + " |")
    print("|" + "---|" * len(keys))
    for r in rows:
        print("| " + " | ".join(str(r.get(k, "")) for k in keys) + " |")


def main() -> None:
    p = argparse.ArgumentParser(description="Sim-to-sim through SONIC's deploy binary.")
    sub = p.add_subparsers(dest="cmd", required=True)
    r = sub.add_parser("run", help="run one session")
    r.add_argument("--robot", required=True, help=f"RobotSpec name or {STOCK!r}")
    r.add_argument("--bundle", required=True, help=f"bundle directory or {RELEASE!r}")
    r.add_argument("--session", choices=("planner", "clip"), default="planner")
    r.add_argument(
        "--clip", default=None,
        help="clip directory name under SONIC's reference/example (default: its first squat; also loaded for planner)",
    )
    r.add_argument("--idle", type=float, default=10.0, help="idle phases [s]")
    r.add_argument(
        "--out", help="run directory (default runs/sim2sim/<time>_<robot>_<bundle>_<session>)"
    )
    r.add_argument("--sonic-workdir", default="~/realmimic-sonic")
    r.add_argument("--engine-cache", default=str(REPO / "runs/sim2sim/.engines"))
    r.add_argument("--tensorrt-root", default=os.environ.get("TensorRT_ROOT", ""))
    r.add_argument(
        "--onnxruntime-root", default=os.environ.get("onnxruntime_ROOT", "/opt/onnxruntime")
    )
    r.add_argument("--cuda-root", default=os.environ.get("CUDAToolkit_ROOT", "/usr/local/cuda"))
    r.add_argument("--sim-dt", type=float, default=0.001, help="physics + PD step [s]")
    r.add_argument("--lowstate-dt", type=float, default=0.002, help="rt/lowstate period [s]")
    r.add_argument("--extra-flags", default="", help="more runtime flags, e.g. gain scales")
    r.add_argument("--perturb", choices=sorted(PERTURBATIONS), default="none", help="robot degradation profile")
    r.add_argument("--seed", type=int, default=0, help="seed of the degradation draws")
    r.add_argument("--init-timeout", type=float, default=1200.0, help="engine builds + INIT [s]")
    r.add_argument("--gpu-min-free-mib", type=int, default=2500, help="refuse to start below")
    r.add_argument("--gpu-abort-free-mib", type=int, default=300, help="kill the runtime below")
    rep = sub.add_parser("report", help="recompute metrics.json / obs_check.json")
    rep.add_argument("run_dir", type=Path)
    s = sub.add_parser("summarize", help="markdown table of runs")
    s.add_argument("run_dirs", type=Path, nargs="+")
    args = p.parse_args()
    if args.cmd == "run":
        if not args.tensorrt_root:
            p.error("set --tensorrt-root or TensorRT_ROOT")
        with exclusive_session():
            print(f"run directory: {run(args)}")
    elif args.cmd == "report":
        report(args.run_dir)
    else:
        summarize(args.run_dirs)


if __name__ == "__main__":
    main()
