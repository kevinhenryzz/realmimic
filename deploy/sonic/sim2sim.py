# Degradation profiles (sonic_sim.py flags) for robustness runs. Magnitudes are moderate estimates of
# the real G1's imperfections, not measurements: ~5 ms each way between state and command, a 2 degree
# IMU mounting tilt and 0.02 rad/s gyro bias, +-0.02 rad joint calibration error plus a 5 degree offset on one
# ankle-roll encoder (a calibration error of the size reported on G1 units), motors at 85 % of their effort limit (heat, battery sag),
# 0.5 kg more head payload than modelled, a low-friction floor.
PERTURBATIONS: dict[str, list[str]] = {
    "none": [],
    "latency": ["--state-delay", "0.005", "--cmd-delay", "0.005"],
    "imu": ["--imu-tilt", "0.035", "--gyro-bias", "0.02", "--gyro-noise", "0.05"],
    "encoders": [
        "--encoder-offset", "0.02", "--encoder-offset-joint", "left_ankle_roll_joint=0.087",
        "--joint-vel-noise", "0.05",
    ],
    "delay10": ["--cmd-delay", "0.010"],
    "delay20": ["--cmd-delay", "0.020"],
    "weak_motors": ["--torque-scale", "0.85"],
    "payload": ["--torso-mass", "0.5"],
    "low_friction": ["--friction", "0.5"],
}  # fmt: skip
# "all": every family at its moderate magnitude (5 ms latency, not the 10/20 ms delay tests).
PERTURBATIONS["all"] = [
    flag for name, flags in PERTURBATIONS.items() if name not in ("none", "delay10", "delay20") for flag in flags
]


# ---------------------------------------------------------------------------- operator session


@dataclass(frozen=True)
class Key:
    """Characters typed on the runtime's keyboard (stdin)."""

    chars: str


@dataclass(frozen=True)
class Wait:
    seconds: float


@dataclass(frozen=True)
class Expect:
    """Wait for a runtime stdout line matching ``pattern``."""

    pattern: str
    timeout: float = 15.0


@dataclass(frozen=True)
class Phase:
    """Start of a named phase (metrics are reported per phase)."""

    name: str


@dataclass(frozen=True)
class Release:
    """Drop the simulator's elastic band (SONIC: press 9 in the viewer)."""


Step = Key | Wait | Expect | Phase | Release


def planner_session(idle: float) -> list[Step]:
    # Keyboard semantics: keyboard_handler.hpp (planner mode). '1' selects SLOW_WALK at 0.2 m/s,
    # each '0' adds 0.1 m/s; W/S set full momentum, R resets it (-> IDLE); Q/E turn the facing
    # direction by +/- pi/6; N enters the squat set (height 0.8 m), '-'/'=' change the height by
    # 0.1 m, '2' is kneel-on-two-legs, P returns to the standing set (idle).
    return [
        Phase("hold"), Key("]"), Wait(1.0), Key("\n"), Expect("motion name is planner_motion"),
        Wait(2.0), Release(), Phase("idle"), Wait(idle),
        Key("1000"), Phase("walk_forward"), Key("w"), Wait(6.0), Key("r"), Phase("stop_1"),
        Wait(3.0), Phase("walk_backward"), Key("s"), Wait(6.0), Key("r"), Phase("stop_2"),
        Wait(3.0), Phase("turn_left"), *[Key("q"), Wait(1.5)] * 3, Wait(1.5),
        Phase("turn_right"), *[Key("e"), Wait(1.5)] * 3, Wait(1.5), Phase("squat"), Key("n"), Wait(2.0), Key("---"), Wait(5.0),
        Phase("kneel"), Key("2"), Wait(8.0), Phase("rise"), Key("1"), Wait(3.0), Key("==="),
        Wait(3.0), Key("p"), Wait(4.0), Phase("idle_end"), Wait(idle),
    ]  # fmt: skip


def clip_session(idle: float, clip_seconds: float) -> list[Step]:
    # Normal mode: the clip is loaded paused at frame 0; T plays it to the end, after which the
    # runtime returns to frame 0 (paused).
    return [
        Phase("hold"), Key("]"), Wait(2.0), Release(), Phase("paused"), Wait(3.0),
        Phase("clip"), Key("t"), Wait(clip_seconds + 1.0), Phase("idle_end"), Wait(idle),
    ]  # fmt: skip


# ---------------------------------------------------------------------------- processes


class Proc:
    """A child process whose stdout is teed to a log file and searchable by regex."""

    def __init__(self, name: str, cmd: list[str], log: Path, **kw: Any):
        self.name = name
        self.lines: list[str] = []
        self.cond = threading.Condition()
        self.log = log.open("w")
        self.log.write("$ " + shlex.join(cmd) + "\n")
        self.p = subprocess.Popen(
            cmd, stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
            text=True, bufsize=1, errors="replace", start_new_session=True, **kw,
        )  # fmt: skip
        threading.Thread(target=self._pump, daemon=True).start()

    def _pump(self) -> None:
        assert self.p.stdout is not None
        for line in self.p.stdout:
            self.log.write(line)
            self.log.flush()
            with self.cond:
                self.lines.append(line.rstrip("\n"))
                self.cond.notify_all()
        with self.cond:
            self.cond.notify_all()

    def alive(self) -> bool:
        return self.p.poll() is None

    def find(self, pattern: str, start: int = 0) -> str | None:
        with self.cond:
            return next((ln for ln in self.lines[start:] if re.search(pattern, ln)), None)

    def wait_for(self, pattern: str, timeout: float) -> str | None:
        deadline = time.monotonic() + timeout
        with self.cond:
            while True:
                hit = next((ln for ln in self.lines if re.search(pattern, ln)), None)
                left = deadline - time.monotonic()
                if hit or left <= 0 or not self.alive():
                    return hit
                self.cond.wait(min(left, 0.5))

    def send(self, text: str) -> None:
        stdin: IO[str] | None = self.p.stdin
        if stdin and self.alive():
            stdin.write(text)
            stdin.flush()

    def stop(self, text: str | None, timeout: float) -> int | None:
        """Ask nicely (``text`` on stdin), then SIGINT, then SIGKILL."""
        if text is not None:
            try:
                self.send(text)
            except BrokenPipeError:
                pass
        for sig in (None, signal.SIGINT, signal.SIGKILL):
            if sig is not None and self.alive():
                os.killpg(self.p.pid, sig)
            try:
                return self.p.wait(timeout)
            except subprocess.TimeoutExpired:
                continue
        return self.p.poll()


def gpu_free_mib() -> int:
    out = subprocess.check_output(
        ["nvidia-smi", "--query-gpu=memory.free", "--format=csv,noheader,nounits"], text=True
    )
    return int(out.split()[0])


def gpu_used_by(pid: int) -> int:
    """GPU memory [MiB] of process ``pid`` (0 if it holds none)."""
    out = subprocess.check_output(
        ["nvidia-smi", "--query-compute-apps=pid,used_memory", "--format=csv,noheader,nounits"],
        text=True,
    )
    for line in out.splitlines():
        p, mem = (int(v) for v in line.split(","))
        if p == pid:
            return mem
    return 0


