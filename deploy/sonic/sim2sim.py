"""Sim-to-sim through SONIC's real deploy binary: MuJoCo sim of a RobotSpec, a policy bundle, a
scripted operator session, and a JSON metrics report.

    uv run python deploy/sonic/sim2sim.py run --robot g1_brainco \\
        --bundle exports/my_bundle --session planner --out runs/sim2sim/my_run
    uv run python deploy/sonic/sim2sim.py report runs/sim2sim/my_run      # recompute reports
    uv run python deploy/sonic/sim2sim.py summarize runs/sim2sim/*/       # markdown table

``--robot``: a RobotSpec name (scene generated by ``realmimic.robots.sim2sim``) or ``sonic_stock``
(SONIC's own ``scene_43dof.xml``). ``--bundle``: a realmimic bundle directory (its ``launch.env``
flags are passed to the runtime) or ``sonic_release`` (SONIC's released encoder + decoder).
``--session``: ``planner`` (start → planner → idle → walk fwd/back 0.5 m/s → turn → squat → kneel
→ rise → idle) or ``clip`` (start → play one reference clip in normal mode → idle).

Processes: ``sonic_sim.py`` in SONIC's sim venv (``setup_sim.sh``) and ``g1_deploy_onnx_ref`` with
keyboard input on its stdin, both on DDS over ``lo``. Outputs in ``--out``: see
``realmimic.eval.sim2sim`` (``metrics.json``) and ``realmimic.eval.sonic_obs_check``
(``obs_check.json``).
"""

